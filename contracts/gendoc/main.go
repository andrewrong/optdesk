// Command gendoc renders one markdown page per dataset schema of contracts/datasets.
package main

import (
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

type schema struct {
	Title       string                     `json:"title"`
	Description string                     `json:"description"`
	Required    []string                   `json:"required"`
	Dataset     string                     `json:"x-dataset"`
	Revision    string                     `json:"x-revision"`
	PrimaryKey  []string                   `json:"x-primary-key"`
	Properties  map[string]json.RawMessage `json:"properties"`
	Defs        map[string]prop            `json:"$defs"`
}

type prop struct {
	Type        json.RawMessage `json:"type"`
	Format      string          `json:"format"`
	Description string          `json:"description"`
	Enum        []string        `json:"enum"`
	Ref         string          `json:"$ref"`
}

// typeNames returns the JSON types of a "type" value and whether null is one of them.
func typeNames(raw json.RawMessage) (names []string, nullable bool) {
	var one string
	var many []string
	if json.Unmarshal(raw, &one) == nil {
		many = []string{one}
	} else {
		_ = json.Unmarshal(raw, &many)
	}
	for _, n := range many {
		if n == "null" {
			nullable = true
			continue
		}
		names = append(names, n)
	}
	return names, nullable
}

func column(name string, p prop, defs map[string]prop, required map[string]bool) string {
	desc := p.Description
	if p.Ref != "" {
		d := defs[strings.TrimPrefix(p.Ref, "#/$defs/")]
		p.Type, p.Enum = d.Type, d.Enum
		if desc == "" {
			desc = d.Description
		}
	}
	names, nullable := typeNames(p.Type)
	typ := strings.Join(names, " or ")
	if len(p.Enum) > 0 {
		typ = "enum(" + strings.Join(p.Enum, ", ") + ")"
	} else if p.Format != "" {
		typ += " (" + p.Format + ")"
	}
	null := "no"
	if nullable || !required[name] {
		null = "yes"
	}
	return fmt.Sprintf("| %s | %s | %s | %s |", name, typ, null, desc)
}

// render returns the markdown page of one dataset schema.
func render(src []byte) (string, error) {
	var s schema
	if err := json.Unmarshal(src, &s); err != nil {
		return "", err
	}
	if s.Dataset == "" || s.Revision == "" {
		return "", errors.New("schema has no x-dataset or x-revision")
	}
	required := map[string]bool{}
	var order []string
	for _, r := range s.Required {
		required[r] = true
		order = append(order, r)
	}
	var rest []string
	for n := range s.Properties {
		if !required[n] {
			rest = append(rest, n)
		}
	}
	sort.Strings(rest)
	order = append(order, rest...)

	var b strings.Builder
	fmt.Fprintf(&b, "<!-- Code generated by contracts/gendoc from contracts/datasets, DO NOT EDIT. -->\n\n")
	fmt.Fprintf(&b, "# %s %s\n\n%s\n\n", s.Dataset, s.Revision, s.Description)
	b.WriteString("| column | type | nullable | meaning |\n|---|---|---|---|\n")
	for _, n := range order {
		raw, ok := s.Properties[n]
		if !ok {
			return "", fmt.Errorf("required property %q is not declared", n)
		}
		var p prop
		if err := json.Unmarshal(raw, &p); err != nil {
			return "", err
		}
		b.WriteString(column(n, p, s.Defs, required) + "\n")
	}
	fmt.Fprintf(&b, "\nPrimary key: (%s)\n", strings.Join(s.PrimaryKey, ", "))
	return b.String(), nil
}

// run renders every *.json file of in to out/<dataset>.md.
func run(in, out string) error {
	files, err := filepath.Glob(filepath.Join(in, "*.json"))
	if err != nil {
		return err
	}
	for _, f := range files {
		src, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		page, err := render(src)
		if err != nil {
			return fmt.Errorf("%s: %w", f, err)
		}
		var s schema
		_ = json.Unmarshal(src, &s)
		if err := os.WriteFile(filepath.Join(out, s.Dataset+".md"), []byte(page), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func main() {
	in := flag.String("in", "contracts/datasets", "directory of dataset schemas")
	out := flag.String("out", "docs/contracts/datasets", "directory of pages")
	flag.Parse()
	if err := run(*in, *out); err != nil {
		fmt.Fprintln(os.Stderr, "gendoc:", err)
		os.Exit(1)
	}
}
