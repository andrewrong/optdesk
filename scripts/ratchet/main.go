// Command ratchet applies the size rule of docs/design/modules.md to the files of a
// change: a source file new in the change has at most 600 lines, a file of the base
// revision over 800 lines is listed in docs/design/ratchet.json and stays under its
// ceiling, and a ceiling is never raised.
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

const (
	ratchetPath = "docs/design/ratchet.json"
	newLimit    = 600
	baseLimit   = 800
)

var sourceExt = map[string]bool{
	".go": true, ".py": true, ".ts": true, ".tsx": true, ".js": true, ".mjs": true, ".sh": true,
}

var generatedMarks = []string{"code generated", "do not edit", "@generated", "generated by"}

// isSource reports whether a file counts: a source extension and no generated header.
func isSource(path string, content []byte) bool {
	if !sourceExt[strings.ToLower(filepath.Ext(path))] {
		return false
	}
	head := content
	for i, n := 0, 0; i < len(content); i++ {
		if content[i] == '\n' {
			if n++; n == 5 {
				head = content[:i]
				break
			}
		}
	}
	low := strings.ToLower(string(head))
	for _, m := range generatedMarks {
		if strings.Contains(low, m) {
			return false
		}
	}
	return true
}

func countLines(b []byte) int {
	n := bytes.Count(b, []byte("\n"))
	if len(b) > 0 && b[len(b)-1] != '\n' {
		n++
	}
	return n
}

// snapshot is what the rule needs of a tree: the lines of each source file.
type snapshot struct {
	lines    map[string]int
	ceilings map[string]int
}

// findings applies the rule to the base paths and ceilings and to the current tree.
func findings(basePaths map[string]bool, baseCeil map[string]int, cur snapshot) []string {
	var out []string
	paths := make([]string, 0, len(cur.lines))
	for p := range cur.lines {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		n := cur.lines[p]
		ceil, listed := cur.ceilings[p]
		switch {
		case !basePaths[p] && n > newLimit:
			out = append(out, fmt.Sprintf("%s: new file has %d lines, limit %d", p, n, newLimit))
		case listed && n > ceil:
			out = append(out, fmt.Sprintf("%s: %d lines, ceiling %d", p, n, ceil))
		case basePaths[p] && !listed && n > baseLimit:
			out = append(out, fmt.Sprintf("%s: %d lines and not listed in %s", p, n, ratchetPath))
		}
	}
	keys := make([]string, 0, len(cur.ceilings))
	for p := range cur.ceilings {
		keys = append(keys, p)
	}
	sort.Strings(keys)
	for _, p := range keys {
		if old, ok := baseCeil[p]; ok && cur.ceilings[p] > old {
			out = append(out, fmt.Sprintf("%s: ceiling raised from %d to %d", p, old, cur.ceilings[p]))
		}
	}
	return out
}

func git(root string, args ...string) ([]byte, error) {
	cmd := exec.CommandContext(context.Background(), "git", append([]string{"-C", root}, args...)...)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("git %s: %w: %s", strings.Join(args, " "), err, strings.TrimSpace(stderr.String()))
	}
	return out, nil
}

// resolveBase turns the --base flag into a revision; empty means the merge base of
// HEAD and origin/main, or of HEAD and main.
func resolveBase(root, flagValue string) (string, error) {
	if flagValue != "" {
		return flagValue, nil
	}
	for _, ref := range []string{"origin/main", "main"} {
		if out, err := git(root, "merge-base", "HEAD", ref); err == nil {
			return strings.TrimSpace(string(out)), nil
		}
	}
	return "", errors.New("no base revision: pass --base")
}

func parseCeilings(b []byte) (map[string]int, error) {
	m := map[string]int{}
	if len(bytes.TrimSpace(b)) == 0 {
		return m, nil
	}
	if err := json.Unmarshal(b, &m); err != nil {
		return nil, fmt.Errorf("%s: %w", ratchetPath, err)
	}
	return m, nil
}

func readBase(root, base string) (map[string]bool, map[string]int, error) {
	out, err := git(root, "ls-tree", "-r", "--name-only", "-z", base)
	if err != nil {
		return nil, nil, err
	}
	paths := map[string]bool{}
	for _, p := range strings.Split(string(out), "\x00") {
		if p != "" {
			paths[p] = true
		}
	}
	var ceil map[string]int
	if paths[ratchetPath] {
		b, err := git(root, "show", base+":"+ratchetPath)
		if err != nil {
			return nil, nil, err
		}
		if ceil, err = parseCeilings(b); err != nil {
			return nil, nil, err
		}
	}
	return paths, ceil, nil
}

func readCurrent(root string) (snapshot, error) {
	snap := snapshot{lines: map[string]int{}}
	out, err := git(root, "ls-files", "-z", "--cached", "--others", "--exclude-standard")
	if err != nil {
		return snap, err
	}
	for _, p := range strings.Split(string(out), "\x00") {
		if p == "" || !sourceExt[strings.ToLower(filepath.Ext(p))] {
			continue
		}
		b, err := os.ReadFile(filepath.Join(root, p))
		if errors.Is(err, os.ErrNotExist) {
			continue // deleted in the working tree
		}
		if err != nil {
			return snap, err
		}
		if isSource(p, b) {
			snap.lines[p] = countLines(b)
		}
	}
	b, err := os.ReadFile(filepath.Join(root, ratchetPath))
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return snap, err
	}
	snap.ceilings, err = parseCeilings(b)
	return snap, err
}

func run(args []string, stdout, stderr io.Writer) int {
	fl := flag.NewFlagSet("ratchet", flag.ContinueOnError)
	fl.SetOutput(stderr)
	root := fl.String("root", ".", "the repository")
	baseFlag := fl.String("base", "", "the base revision (default: merge base with origin/main)")
	if err := fl.Parse(args); err != nil {
		return 2
	}
	base, err := resolveBase(*root, *baseFlag)
	var paths map[string]bool
	var baseCeil map[string]int
	var cur snapshot
	if err == nil {
		paths, baseCeil, err = readBase(*root, base)
	}
	if err == nil {
		cur, err = readCurrent(*root)
	}
	if err != nil {
		fmt.Fprintln(stderr, "ratchet:", err)
		return 2
	}
	bad := findings(paths, baseCeil, cur)
	for _, f := range bad {
		fmt.Fprintln(stderr, "ratchet:", f)
	}
	if len(bad) > 0 {
		return 1
	}
	fmt.Fprintln(stdout, "ratchet: ok")
	return 0
}

func main() {
	os.Exit(run(os.Args[1:], os.Stdout, os.Stderr))
}
