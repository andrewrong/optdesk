package main

import (
	"bytes"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// repo is a temporary git repository with one commit, the base.
type repo struct {
	t    *testing.T
	dir  string
	base string
}

func gitIn(t *testing.T, dir string, args ...string) string {
	t.Helper()
	cmd := exec.CommandContext(t.Context(), "git", append([]string{"-C", dir}, args...)...)
	cmd.Env = append(os.Environ(),
		"GIT_AUTHOR_NAME=t", "GIT_AUTHOR_EMAIL=t@users.noreply.github.com",
		"GIT_COMMITTER_NAME=t", "GIT_COMMITTER_EMAIL=t@users.noreply.github.com",
		"GIT_CONFIG_GLOBAL=/dev/null", "GIT_CONFIG_SYSTEM=/dev/null")
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("git %v: %v: %s", args, err, out)
	}
	return strings.TrimSpace(string(out))
}

func lines(n int) string {
	return strings.Repeat("x := 1\n", n)
}

func put(t *testing.T, dir, rel, content string) {
	t.Helper()
	p := filepath.Join(dir, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}

// newRepo commits the files as the base revision.
func newRepo(t *testing.T, files map[string]string) *repo {
	t.Helper()
	dir := t.TempDir()
	gitIn(t, dir, "init", "-q", "--template=")
	put(t, dir, "README.md", "x\n")
	for p, c := range files {
		put(t, dir, p, c)
	}
	gitIn(t, dir, "add", "-A")
	gitIn(t, dir, "commit", "-q", "-m", "base")
	return &repo{t: t, dir: dir, base: gitIn(t, dir, "rev-parse", "HEAD")}
}

func (r *repo) check() (int, string) {
	var out, errb bytes.Buffer
	code := run([]string{"--root", r.dir, "--base", r.base}, &out, &errb)
	return code, errb.String() + out.String()
}

func want(t *testing.T, r *repo, code int, needle string) {
	t.Helper()
	got, out := r.check()
	if got != code || !strings.Contains(out, needle) {
		t.Fatalf("exit %d output %q, want exit %d containing %q", got, out, code, needle)
	}
}

func TestRatchetNewFileOver600(t *testing.T) {
	t.Parallel()
	r := newRepo(t, nil)
	put(t, r.dir, "a.go", lines(600))
	want(t, r, 0, "ok")
	put(t, r.dir, "a.go", lines(601))
	want(t, r, 1, "a.go: new file has 601 lines")
}

func TestRatchetCopyCountsAsNew(t *testing.T) {
	t.Parallel()
	r := newRepo(t, map[string]string{"old.go": lines(700)})
	want(t, r, 0, "ok")
	put(t, r.dir, "copy.go", lines(700))
	want(t, r, 1, "copy.go: new file has 700 lines")
}

func TestRatchetUnlistedOver800(t *testing.T) {
	t.Parallel()
	r := newRepo(t, map[string]string{"big.go": lines(801)})
	want(t, r, 1, "big.go: 801 lines and not listed")
	put(t, r.dir, "docs/design/ratchet.json", `{"big.go": 801}`)
	want(t, r, 0, "ok")
}

func TestRatchetOverCeiling(t *testing.T) {
	t.Parallel()
	r := newRepo(t, map[string]string{"big.go": lines(850), "docs/design/ratchet.json": `{"big.go": 850}`})
	want(t, r, 0, "ok")
	put(t, r.dir, "big.go", lines(851))
	want(t, r, 1, "big.go: 851 lines, ceiling 850")
}

func TestRatchetCeilingRaised(t *testing.T) {
	t.Parallel()
	r := newRepo(t, map[string]string{"big.go": lines(850), "docs/design/ratchet.json": `{"big.go": 850}`})
	put(t, r.dir, "docs/design/ratchet.json", `{"big.go": 900}`)
	want(t, r, 1, "big.go: ceiling raised from 850 to 900")
	put(t, r.dir, "docs/design/ratchet.json", `{"big.go": 840}`)
	put(t, r.dir, "big.go", lines(840))
	want(t, r, 0, "ok")
}

func TestRatchetCountsSourceFilesOnly(t *testing.T) {
	t.Parallel()
	r := newRepo(t, nil)
	put(t, r.dir, "pnpm-lock.yaml", lines(5000))
	put(t, r.dir, "data.json", lines(5000))
	put(t, r.dir, "config.toml", lines(5000))
	put(t, r.dir, "NOTES.md", lines(5000))
	put(t, r.dir, "gen.go", "// Code generated by x. DO NOT EDIT.\n"+lines(5000))
	put(t, r.dir, "gen.ts", "// a\n// b\n// c\n// @generated\n"+lines(5000))
	want(t, r, 0, "ok")
	put(t, r.dir, "late.go", "// a\n// b\n// c\n// d\n// e\n// DO NOT EDIT\n"+lines(700))
	want(t, r, 1, "late.go: new file has 706 lines")
}
