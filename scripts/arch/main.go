// Command arch derives arch.toml and .go-arch-lint.yml from the depends column of
// docs/design/modules.md and from the tree.
//
// The tree tells the kind of each internal/<row>/<package> directory by its files:
// generated, declarations-only (api.go alone), test kit (a non-test file imports
// "testing") or implementation. go-arch-lint also rejects a component whose directory
// is absent and flags a package that belongs to no component.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/parser"
	"go/token"
	"io"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strings"
)

const (
	tomlFile = "arch.toml"
	ymlFile  = ".go-arch-lint.yml"
	header   = "Generated by scripts/arch from docs/design/modules.md. Do not edit."
)

// row is one line of the table under "## Modules".
type row struct {
	name    string
	paths   []string
	entry   []string
	depends []string
}

// component is one go-arch-lint component: a package directory and its import list.
type component struct {
	name string
	dir  string
	deps []string
}

var internalGlob = regexp.MustCompile(`^internal/([^/*]+)/\*\*$`)

// parseModules reads the rows of the table under "## Modules".
func parseModules(text string) ([]row, error) {
	_, table, ok := strings.Cut(text, "\n## Modules\n")
	if !ok {
		return nil, errors.New("no '## Modules' heading")
	}
	var rows []row
	for _, line := range strings.Split(table, "\n") {
		if strings.HasPrefix(line, "## ") {
			break
		}
		if !strings.HasPrefix(line, "|") {
			continue
		}
		cells := strings.Split(strings.TrimSuffix(strings.TrimPrefix(strings.TrimSpace(line), "|"), "|"), "|")
		if len(cells) != 5 || strings.TrimSpace(cells[0]) == "module" || strings.HasPrefix(strings.TrimSpace(cells[0]), "---") {
			continue
		}
		rows = append(rows, row{
			name:    strings.TrimSpace(cells[0]),
			paths:   strings.Fields(cells[1]),
			entry:   strings.Fields(cells[2]),
			depends: strings.Fields(cells[4]),
		})
	}
	if len(rows) == 0 {
		return nil, errors.New("no rows under '## Modules'")
	}
	return rows, nil
}

// rootName gives the component name of a row, or "" when the row has no Go package.
func rootName(r row) (name, dir string) {
	for _, p := range r.paths {
		if m := internalGlob.FindStringSubmatch(p); m != nil {
			return m[1], "internal/" + m[1]
		}
		if p == "cmd/**" {
			return "ot", "cmd/ot"
		}
	}
	return "", ""
}

// generated lists the generated sub-packages; each gets an empty may_import.
var generated = []string{"internal/contracts/gen", "internal/contracts/genpb"}

// importableGenerated lists the generated packages that the sub-packages of the dependents
// of their row may import; the other generated packages are importable by their root only.
var importableGenerated = []string{"internal/contracts/genpb"}

// sharedSub is the sub-package that the other sub-packages of its row may import, and that
// imports no sibling; no module outside its row imports it, except ot, which imports it
// for the rows of its depends cell.
const sharedSub = "shared"

// kind is what the files of a package directory say about it.
type kind int

const (
	kindImpl      kind = iota // any other package with a non-test .go file
	kindGenerated             // listed in generated, never an implementation package
	kindDecl                  // api.go and no other non-test .go file except doc.go
	kindKit                   // a non-test file imports "testing"
)

// pkg is a package directory internal/<a>/<b> found in the tree, with the row that owns it.
type pkg struct {
	dir  string
	kind kind
	row  string
}

// ownerRow gives the first row whose path glob matches dir, or "".
func ownerRow(rows []row, dir string) string {
	for _, r := range rows {
		for _, p := range r.paths {
			if base, ok := strings.CutSuffix(p, "/**"); ok {
				if dir == base || strings.HasPrefix(dir, base+"/") {
					return r.name
				}
			} else if ok, _ := path.Match(p, dir); ok {
				return r.name
			}
		}
	}
	return ""
}

// classify reads the non-test .go files of the package directory abs (rel is its tree path);
// a directory with none gives ok false.
func classify(abs, rel string) (k kind, ok bool, err error) {
	ents, err := os.ReadDir(abs)
	if err != nil {
		return 0, false, err
	}
	var files []string
	for _, e := range ents {
		n := e.Name()
		if !e.IsDir() && strings.HasSuffix(n, ".go") && !strings.HasSuffix(n, "_test.go") {
			files = append(files, n)
		}
	}
	if len(files) == 0 {
		return 0, false, nil
	}
	if slices.Contains(generated, rel) {
		return kindGenerated, true, nil
	}
	api, other := false, false
	for _, n := range files {
		f, err := parser.ParseFile(token.NewFileSet(), filepath.Join(abs, n), nil, parser.ImportsOnly)
		if err != nil {
			return 0, false, err
		}
		for _, imp := range f.Imports {
			if imp.Path.Value == `"testing"` {
				return kindKit, true, nil
			}
		}
		if n == "api.go" {
			api = true
		} else if n != "doc.go" {
			other = true
		}
	}
	if api && !other {
		return kindDecl, true, nil
	}
	return kindImpl, true, nil
}

// discover classifies every internal/<a>/<b>[/...] directory, at any depth, of dirs (as goDirs lists them).
func discover(root string, dirs []string, rows []row) ([]pkg, error) {
	var out []pkg
	for _, d := range dirs {
		parts := strings.Split(d, "/")
		if len(parts) < 3 || parts[0] != "internal" {
			continue
		}
		k, ok, err := classify(filepath.Join(root, filepath.FromSlash(d)), d)
		if err != nil {
			return nil, err
		}
		if ok {
			out = append(out, pkg{d, k, ownerRow(rows, d)})
		}
	}
	return out, nil
}

// owned gives the components (without "internal/") of the packages of a row of one of the kinds.
func owned(pkgs []pkg, rowName string, kinds ...kind) []string {
	var out []string
	for _, p := range pkgs {
		if p.row == rowName && slices.Contains(kinds, p.kind) {
			out = append(out, strings.TrimPrefix(p.dir, "internal/"))
		}
	}
	return out
}

// addUnique appends the names of add that xs lacks, leaving self out.
func addUnique(xs, add []string, self string) []string {
	for _, a := range add {
		if a != self && !slices.Contains(xs, a) {
			xs = append(xs, a)
		}
	}
	return xs
}

// listedImports gives, for each root component, the sub-package components that its own
// sub-packages may import: the declarations-only packages and test kits of the rows it
// depends on, the importable generated packages of those rows, and its own declarations-only packages.
func listedImports(rows []row, pkgs []pkg) map[string][]string {
	out := map[string][]string{}
	for _, r := range rows {
		name, _ := rootName(r)
		if name == "" {
			continue
		}
		for _, d := range r.depends {
			out[name] = append(out[name], owned(pkgs, d, kindDecl, kindKit)...)
			for _, g := range importableGenerated {
				if ownerRow(rows, g) == d {
					out[name] = append(out[name], strings.TrimPrefix(g, "internal/"))
				}
			}
		}
		out[name] = append(out[name], owned(pkgs, r.name, kindDecl)...)
	}
	return out
}

// derive builds the components from the table and the discovered packages (arch.toml): the
// root of each row, its sub-packages, and contracts/gen and contracts/genpb. cmd/ot imports
// the root of each row in its depends cell and every discovered implementation or
// declarations-only package of those rows.
func derive(rows []row, pkgs []pkg) ([]component, error) {
	byRow := map[string]string{}
	for _, r := range rows {
		if n, _ := rootName(r); n != "" {
			byRow[r.name] = n
		}
	}
	dirs := slices.Clone(generated)
	for _, p := range pkgs {
		dirs = append(dirs, p.dir)
	}
	var out []component
	for _, r := range rows {
		name, dir := rootName(r)
		if name == "" {
			continue
		}
		var deps []string
		for _, d := range r.depends {
			dn, ok := byRow[d]
			if !ok {
				return nil, fmt.Errorf("row %s depends on %s, which has no Go package", r.name, d)
			}
			deps = append(deps, dn)
		}
		for _, d := range r.depends {
			if name == "ot" {
				deps = append(deps, owned(pkgs, d, kindImpl, kindDecl)...)
			} else {
				deps = addUnique(deps, owned(pkgs, d, kindDecl), "")
			}
		}
		if name == "contracts" {
			deps = append(deps, "contracts/gen")
		}
		out = append(out, component{name, dir, deps})
		if name == "ot" {
			continue
		}
		for _, sub := range subsOf(name, dirs) {
			subs := addUnique(subDeps(deps, name), owned(pkgs, r.name, kindDecl), name+"/"+sub)
			if sub != sharedSub && slices.Contains(dirs, "internal/"+name+"/"+sharedSub) {
				subs = addUnique(subs, []string{name + "/" + sharedSub}, "")
			}
			if slices.Contains(generated, "internal/"+name+"/"+sub) {
				subs = nil // generated output imports no component of the repository
			}
			out = append(out, component{name + "/" + sub, dir + "/" + sub, subs})
		}
	}
	return out, nil
}

func subsOf(name string, pkgs []string) []string {
	var out []string
	for _, p := range pkgs {
		if rest, ok := strings.CutPrefix(p, "internal/"+name+"/"); ok {
			out = append(out, rest)
		}
	}
	sort.Strings(out)
	return slices.Compact(out)
}

// subDeps is what a sub-package may import: the row's roots and the root of its own row.
func subDeps(rootDeps []string, name string) []string {
	var out []string
	for _, d := range rootDeps {
		if d != name+"/gen" {
			out = append(out, d)
		}
	}
	return append(out, name)
}

func renderTOML(cs []component) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "# %s\n", header)
	for _, c := range cs {
		fmt.Fprintf(&b, "\n[component.%q]\nin = %q\nmay_import = [%s]\n", c.name, c.dir, quoteList(c.deps))
	}
	return b.Bytes()
}

func quoteList(xs []string) string {
	q := make([]string, len(xs))
	for i, x := range xs {
		q[i] = fmt.Sprintf("%q", x)
	}
	return strings.Join(q, ", ")
}

// goDirs lists the directories under root that hold a .go file, relative and sorted.
func goDirs(root string) ([]string, error) {
	seen := map[string]bool{}
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		n := d.Name()
		if d.IsDir() && p != root && (strings.HasPrefix(n, ".") || n == "node_modules" || n == "web" || n == "vendor") {
			return filepath.SkipDir
		}
		if !d.IsDir() && strings.HasSuffix(n, ".go") {
			rel, _ := filepath.Rel(root, filepath.Dir(p))
			seen[filepath.ToSlash(rel)] = true
		}
		return nil
	})
	var out []string
	for d := range seen {
		out = append(out, d)
	}
	sort.Strings(out)
	return out, err
}

// deriveTree narrows the derived components to the tree: a component exists when its
// directory holds Go files, and every package under internal/<row>/ is a component.
// A sub-package may also import the sub-packages that the entry cell of a row its row
// depends on lists (listed, by root name).
func deriveTree(table []component, dirs []string, listed map[string][]string) (comps []component, exclude []string) {
	have := map[string]bool{}
	for _, d := range dirs {
		have[d] = true
	}
	rootDeps := map[string][]component{}
	var order []component
	known := map[string]bool{}
	for _, c := range table {
		if !strings.Contains(c.name, "/") {
			rootDeps[c.name] = []component{c}
		}
	}
	for _, c := range table {
		if have[c.dir] {
			order = append(order, c)
			known[c.dir] = true
		}
	}
	for _, d := range dirs {
		root, rest, ok := strings.Cut(strings.TrimPrefix(d, "internal/"), "/")
		if !strings.HasPrefix(d, "internal/") || !ok || known[d] {
			continue
		}
		if rc, ok := rootDeps[root]; ok {
			order = append(order, component{root + "/" + rest, d, subDeps(rc[0].deps, root)})
			known[d] = true
		}
	}
	for i, c := range order {
		if root, _, ok := strings.Cut(c.name, "/"); ok {
			order[i].deps = addUnique(slices.Clone(c.deps), listed[root], c.name)
		}
	}
	names := map[string]bool{}
	for _, c := range order {
		names[c.name] = true
	}
	for _, c := range order {
		var deps []string
		for _, d := range c.deps {
			if names[d] {
				deps = append(deps, d)
			}
		}
		comps = append(comps, component{c.name, c.dir, deps})
	}
	for _, d := range dirs {
		if !known[d] && !strings.HasPrefix(d, "internal/") {
			exclude = append(exclude, d)
		}
	}
	return comps, exclude
}

func renderYAML(cs []component, exclude []string) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "# %s\nversion: 3\nworkdir: .\nallow:\n  depOnAnyVendor: true\nexcludeFiles:\n  - \"^.*_test\\\\.go$\"\n", header)
	if len(exclude) > 0 {
		b.WriteString("exclude:\n")
		for _, e := range exclude {
			fmt.Fprintf(&b, "  - %s\n", e)
		}
	}
	b.WriteString("components:\n")
	for _, c := range cs {
		fmt.Fprintf(&b, "  %s:\n    in: %s\n", c.name, c.dir)
	}
	b.WriteString("deps:\n")
	for _, c := range cs {
		if len(c.deps) == 0 {
			continue // go-arch-lint rejects an empty list; no entry means no import
		}
		fmt.Fprintf(&b, "  %s:\n    mayDependOn:\n", c.name)
		for _, d := range c.deps {
			fmt.Fprintf(&b, "      - %s\n", d)
		}
	}
	return b.Bytes()
}

// generate returns the contents of arch.toml and .go-arch-lint.yml for a modules.md text
// and a project tree.
func generate(modules, root string) (toml, yml []byte, err error) {
	rows, err := parseModules(modules)
	if err != nil {
		return nil, nil, err
	}
	dirs, err := goDirs(root)
	if err != nil {
		return nil, nil, err
	}
	pkgs, err := discover(root, dirs, rows)
	if err != nil {
		return nil, nil, err
	}
	table, err := derive(rows, pkgs)
	if err != nil {
		return nil, nil, err
	}
	comps, exclude := deriveTree(table, dirs, listedImports(rows, pkgs))
	return renderTOML(table), renderYAML(comps, exclude), nil
}

func run(args []string, stdout, stderr io.Writer) int {
	fl := flag.NewFlagSet("arch", flag.ContinueOnError)
	fl.SetOutput(stderr)
	modules := fl.String("modules", "docs/design/modules.md", "the module map")
	root := fl.String("root", ".", "the project root")
	if err := fl.Parse(args); err != nil {
		return 2
	}
	text, err := os.ReadFile(*modules)
	if err != nil {
		fmt.Fprintln(stderr, "arch:", err)
		return 2
	}
	toml, yml, err := generate(string(text), *root)
	if err != nil {
		fmt.Fprintln(stderr, "arch:", err)
		return 2
	}
	files := map[string][]byte{tomlFile: toml, ymlFile: yml}
	for _, name := range []string{tomlFile, ymlFile} {
		if err := os.WriteFile(filepath.Join(*root, name), files[name], 0o600); err != nil {
			fmt.Fprintln(stderr, "arch:", err)
			return 2
		}
	}
	return 0
}

func main() {
	os.Exit(run(os.Args[1:], os.Stdout, os.Stderr))
}
