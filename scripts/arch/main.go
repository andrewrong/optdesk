// Command arch derives arch.toml and .go-arch-lint.yml from the depends column of
// docs/design/modules.md, and with --check fails when the committed files differ.
//
// arch.toml depends on the table only. .go-arch-lint.yml also reads the tree, because
// go-arch-lint rejects a component whose directory is absent and flags a package that
// belongs to no component.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strings"
)

const (
	tomlFile = "arch.toml"
	ymlFile  = ".go-arch-lint.yml"
	header   = "Generated by scripts/arch from docs/design/modules.md. Do not edit."
)

// row is one line of the table under "## Modules".
type row struct {
	name    string
	paths   []string
	depends []string
}

// component is one go-arch-lint component: a package directory and its import list.
type component struct {
	name string
	dir  string
	deps []string
}

var (
	internalGlob = regexp.MustCompile(`^internal/([^/*]+)/\*\*$`)
	implPackage  = regexp.MustCompile("`(internal/[a-z0-9_]+/[a-z0-9_]+)`")
)

// parseModules reads the rows of the table under "## Modules".
func parseModules(text string) ([]row, error) {
	_, table, ok := strings.Cut(text, "\n## Modules\n")
	if !ok {
		return nil, errors.New("no '## Modules' heading")
	}
	var rows []row
	for _, line := range strings.Split(table, "\n") {
		if strings.HasPrefix(line, "## ") {
			break
		}
		if !strings.HasPrefix(line, "|") {
			continue
		}
		cells := strings.Split(strings.TrimSuffix(strings.TrimPrefix(strings.TrimSpace(line), "|"), "|"), "|")
		if len(cells) != 5 || strings.TrimSpace(cells[0]) == "module" || strings.HasPrefix(strings.TrimSpace(cells[0]), "---") {
			continue
		}
		rows = append(rows, row{
			name:    strings.TrimSpace(cells[0]),
			paths:   strings.Fields(cells[1]),
			depends: strings.Fields(cells[4]),
		})
	}
	if len(rows) == 0 {
		return nil, errors.New("no rows under '## Modules'")
	}
	return rows, nil
}

// parseImpl reads the implementation packages that the composition root may import:
// the backticked internal/<a>/<b> paths between "these eleven" and "Any other import".
func parseImpl(text string) ([]string, error) {
	_, rest, ok := strings.Cut(text, "these eleven")
	if !ok {
		return nil, errors.New("no 'these eleven' list")
	}
	list, _, _ := strings.Cut(rest, "Any other import")
	var out []string
	for _, m := range implPackage.FindAllStringSubmatch(list, -1) {
		out = append(out, m[1])
	}
	if len(out) == 0 {
		return nil, errors.New("the implementation list is empty")
	}
	return out, nil
}

// rootName gives the component name of a row, or "" when the row has no Go package.
func rootName(r row) (name, dir string) {
	for _, p := range r.paths {
		if m := internalGlob.FindStringSubmatch(p); m != nil {
			return m[1], "internal/" + m[1]
		}
		if p == "cmd/**" {
			return "ot", "cmd/ot"
		}
	}
	return "", ""
}

// generated lists the generated sub-packages; each gets an empty may_import.
var generated = []string{"internal/contracts/gen", "internal/contracts/genpb"}

// derive builds the components from the table alone (arch.toml): the root of each row,
// the implementation packages named in the text, contracts/gen and contracts/genpb.
func derive(rows []row, impl []string) ([]component, error) {
	byRow := map[string]string{}
	for _, r := range rows {
		if n, _ := rootName(r); n != "" {
			byRow[r.name] = n
		}
	}
	var out []component
	for _, r := range rows {
		name, dir := rootName(r)
		if name == "" {
			continue
		}
		var deps []string
		for _, d := range r.depends {
			dn, ok := byRow[d]
			if !ok {
				return nil, fmt.Errorf("row %s depends on %s, which has no Go package", r.name, d)
			}
			deps = append(deps, dn)
		}
		if name == "ot" {
			deps = append(deps, subNames(impl)...)
		}
		if name == "contracts" {
			deps = append(deps, "contracts/gen")
		}
		out = append(out, component{name, dir, deps})
		if name == "ot" {
			continue
		}
		for _, sub := range subsOf(name, append(append([]string{}, impl...), generated...)) {
			subs := subDeps(deps, name)
			if slices.Contains(generated, "internal/"+name+"/"+sub) {
				subs = nil // generated output imports no component of the repository
			}
			out = append(out, component{name + "/" + sub, dir + "/" + sub, subs})
		}
	}
	return out, nil
}

func subNames(pkgs []string) []string {
	var out []string
	for _, p := range pkgs {
		out = append(out, strings.TrimPrefix(p, "internal/"))
	}
	return out
}

func subsOf(name string, pkgs []string) []string {
	var out []string
	for _, p := range pkgs {
		if rest, ok := strings.CutPrefix(p, "internal/"+name+"/"); ok {
			out = append(out, rest)
		}
	}
	sort.Strings(out)
	return out
}

// subDeps is what a sub-package may import: the row's roots and the root of its own row.
func subDeps(rootDeps []string, name string) []string {
	var out []string
	for _, d := range rootDeps {
		if d != name+"/gen" {
			out = append(out, d)
		}
	}
	return append(out, name)
}

func renderTOML(cs []component) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "# %s\n", header)
	for _, c := range cs {
		fmt.Fprintf(&b, "\n[component.%q]\nin = %q\nmay_import = [%s]\n", c.name, c.dir, quoteList(c.deps))
	}
	return b.Bytes()
}

func quoteList(xs []string) string {
	q := make([]string, len(xs))
	for i, x := range xs {
		q[i] = fmt.Sprintf("%q", x)
	}
	return strings.Join(q, ", ")
}

// goDirs lists the directories under root that hold a .go file, relative and sorted.
func goDirs(root string) ([]string, error) {
	seen := map[string]bool{}
	err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		n := d.Name()
		if d.IsDir() && p != root && (strings.HasPrefix(n, ".") || n == "node_modules" || n == "web" || n == "vendor") {
			return filepath.SkipDir
		}
		if !d.IsDir() && strings.HasSuffix(n, ".go") {
			rel, _ := filepath.Rel(root, filepath.Dir(p))
			seen[filepath.ToSlash(rel)] = true
		}
		return nil
	})
	var out []string
	for d := range seen {
		out = append(out, d)
	}
	sort.Strings(out)
	return out, err
}

// deriveTree narrows the derived components to the tree: a component exists when its
// directory holds Go files, and every package under internal/<row>/ is a component.
func deriveTree(table []component, dirs []string) (comps []component, exclude []string) {
	have := map[string]bool{}
	for _, d := range dirs {
		have[d] = true
	}
	rootDeps := map[string][]component{}
	var order []component
	known := map[string]bool{}
	for _, c := range table {
		if !strings.Contains(c.name, "/") {
			rootDeps[c.name] = []component{c}
		}
	}
	for _, c := range table {
		if have[c.dir] {
			order = append(order, c)
			known[c.dir] = true
		}
	}
	for _, d := range dirs {
		root, rest, ok := strings.Cut(strings.TrimPrefix(d, "internal/"), "/")
		if !strings.HasPrefix(d, "internal/") || !ok || known[d] {
			continue
		}
		if rc, ok := rootDeps[root]; ok {
			order = append(order, component{root + "/" + rest, d, subDeps(rc[0].deps, root)})
			known[d] = true
		}
	}
	names := map[string]bool{}
	for _, c := range order {
		names[c.name] = true
	}
	for _, c := range order {
		var deps []string
		for _, d := range c.deps {
			if names[d] {
				deps = append(deps, d)
			}
		}
		comps = append(comps, component{c.name, c.dir, deps})
	}
	for _, d := range dirs {
		if !known[d] && !strings.HasPrefix(d, "internal/") {
			exclude = append(exclude, d)
		}
	}
	return comps, exclude
}

func renderYAML(cs []component, exclude []string) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "# %s\nversion: 3\nworkdir: .\nallow:\n  depOnAnyVendor: true\nexcludeFiles:\n  - \"^.*_test\\\\.go$\"\n", header)
	if len(exclude) > 0 {
		b.WriteString("exclude:\n")
		for _, e := range exclude {
			fmt.Fprintf(&b, "  - %s\n", e)
		}
	}
	b.WriteString("components:\n")
	for _, c := range cs {
		fmt.Fprintf(&b, "  %s:\n    in: %s\n", c.name, c.dir)
	}
	b.WriteString("deps:\n")
	for _, c := range cs {
		if len(c.deps) == 0 {
			continue // go-arch-lint rejects an empty list; no entry means no import
		}
		fmt.Fprintf(&b, "  %s:\n    mayDependOn:\n", c.name)
		for _, d := range c.deps {
			fmt.Fprintf(&b, "      - %s\n", d)
		}
	}
	return b.Bytes()
}

// generate returns the contents of arch.toml and .go-arch-lint.yml for a modules.md text
// and a project tree.
func generate(modules, root string) (toml, yml []byte, err error) {
	rows, err := parseModules(modules)
	if err != nil {
		return nil, nil, err
	}
	impl, err := parseImpl(modules)
	if err != nil {
		return nil, nil, err
	}
	table, err := derive(rows, impl)
	if err != nil {
		return nil, nil, err
	}
	dirs, err := goDirs(root)
	if err != nil {
		return nil, nil, err
	}
	comps, exclude := deriveTree(table, dirs)
	return renderTOML(table), renderYAML(comps, exclude), nil
}

func run(args []string, stdout, stderr io.Writer) int {
	fl := flag.NewFlagSet("arch", flag.ContinueOnError)
	fl.SetOutput(stderr)
	check := fl.Bool("check", false, "fail when the committed files differ from the derivation")
	modules := fl.String("modules", "docs/design/modules.md", "the module map")
	root := fl.String("root", ".", "the project root")
	if err := fl.Parse(args); err != nil {
		return 2
	}
	text, err := os.ReadFile(*modules)
	if err != nil {
		fmt.Fprintln(stderr, "arch:", err)
		return 2
	}
	toml, yml, err := generate(string(text), *root)
	if err != nil {
		fmt.Fprintln(stderr, "arch:", err)
		return 2
	}
	files := map[string][]byte{tomlFile: toml, ymlFile: yml}
	bad := 0
	for _, name := range []string{tomlFile, ymlFile} {
		path := filepath.Join(*root, name)
		if !*check {
			if err := os.WriteFile(path, files[name], 0o600); err != nil {
				fmt.Fprintln(stderr, "arch:", err)
				return 2
			}
			continue
		}
		got, err := os.ReadFile(path)
		if err != nil || !bytes.Equal(got, files[name]) {
			fmt.Fprintf(stderr, "arch: %s does not match docs/design/modules.md; run go run ./scripts/arch\n", name)
			bad++
		}
	}
	if bad > 0 {
		return 1
	}
	if *check {
		fmt.Fprintln(stdout, "arch: ok")
	}
	return 0
}

func main() {
	os.Exit(run(os.Args[1:], os.Stdout, os.Stderr))
}
